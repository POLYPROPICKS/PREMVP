#!/usr/bin/env python3
"""Deterministically build the Box B pilot insert and the single DBClone operator script.

Inputs : receipts/receipts_index.json + raw bodies, the migration SQL (embedded verbatim).
Outputs: pilot_insert.sql, operator_dbclone_box_b_v1.sql, build_manifest.json
Only receipts that were actually fetched are emitted; nothing is synthesised and
has_paper_decision is never written to Box B.
"""
import hashlib, json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
MIG = HERE.parent / "migrations" / "20261013130000_market_outcome_box_b_authority_v1.sql"
RCPT = HERE / "receipts"


def lit(s):
    return "null" if s is None else "'" + s.replace("'", "''") + "'"


def dollar(body):
    assert "\x00" not in body
    tag = "bb"
    while f"${tag}$" in body:
        tag += "x"
    return f"${tag}${body}${tag}$"


def receipt_insert(rc):
    raw = (RCPT / rc["file"]).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == rc["raw_digest"], rc["file"]
    body = raw.decode("utf-8")
    assert body.encode("utf-8") == raw
    return ("insert into public.market_outcome_provider_receipts\n"
            "  (provider, request_kind, request_key, request_url, http_status, fetch_error, fetched_at, raw_body, raw_digest)\n"
            f"values ({lit(rc['provider'])}, {lit(rc['request_kind'])}, {lit(rc['request_key'])}, {lit(rc['request_url'])}, "
            f"{rc['http_status'] if rc['http_status'] is not None else 'null'}, {lit(rc['fetch_error'])}, "
            f"{lit(rc['fetched_at'])}::timestamptz, {dollar(body)}, {lit(rc['raw_digest'])})\n"
            "on conflict (provider, request_kind, request_key, raw_digest) do nothing;\n")


def rev_insert(x):
    c, g, k = x["classification"], x["gamma_receipt"], x["clob_receipt"]
    sel = lambda r: ("(select receipt_id from public.market_outcome_provider_receipts where provider = "
                     f"{lit(r['provider'])} and request_kind = {lit(r['request_kind'])} and request_key = {lit(r['request_key'])} "
                     f"and raw_digest = {lit(r['raw_digest'])})")
    checked = max(g["fetched_at"], k["fetched_at"])
    return ("insert into public.market_outcome_revisions\n"
            "  (condition_id, outcome_status, winner_token_id, gamma_winner_token_id, clob_winner_token_id, market_token_ids,\n"
            "   gamma_receipt_id, clob_receipt_id, resolved_at, resolution_time_source, checked_at, status_reason)\n"
            f"values ({lit(x['condition_id'])}, {lit(c['status'])}, {lit(c['winner_token_id'])}, {lit(c['gamma_winner_token_id'])}, "
            f"{lit(c['clob_winner_token_id'])}, {lit(json.dumps(c['market_token_ids']))}::jsonb,\n"
            f"  {sel(g)},\n  {sel(k)},\n"
            f"  {lit(c['resolved_at'])}::timestamptz, {lit(c['resolution_time_source'])}, {lit(checked)}::timestamptz, {lit(c['reason'])});\n")


def main():
    idx = json.loads((RCPT / "receipts_index.json").read_text())
    parts = ["-- Box B pilot: provider-verified outcomes only (generated by build_operator_sql.py).\n"
             "-- Re-running is idempotent: receipts dedupe on digest, revisions on evidence_digest.\n"]
    n_rc = 0
    for x in idx:
        if "token_lookup_receipt" in x:
            parts.append(receipt_insert(x["token_lookup_receipt"])); n_rc += 1
        if x["classification"]["status"] == "LOOKUP_FAILED" and "gamma_receipt" not in x:
            continue
        parts.append(receipt_insert(x["gamma_receipt"])); parts.append(receipt_insert(x["clob_receipt"])); n_rc += 2
    for x in idx:
        if "gamma_receipt" in x:
            parts.append(rev_insert(x))
    pilot = "".join(parts)
    n_rev = sum(1 for x in idx if "gamma_receipt" in x)

    mig = MIG.read_text()
    guard = f"""-- DBCLONE ONLY: nppznoujvnyjargjkmnv. ONE atomic script: Box B create + provider-backed pilot + fail-closed checks.
-- Paste into the Research DBClone SQL Editor. Do NOT run on Production. Any failure rolls back everything.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '120s';
do $$
declare registered boolean;
begin
  if to_regclass('public.research_inplay_core_path_observations') is null then
    raise exception 'BOX_B_GUARD: not a Research DBClone (research_inplay_core_path_observations missing)';
  end if;
  if to_regclass('public.market_outcome_provider_receipts') is not null
     or to_regclass('public.market_outcome_revisions') is not null then
    raise exception 'BOX_B_GUARD: Box B already exists';
  end if;
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select exists (select 1 from supabase_migrations.schema_migrations where version = ''20261013130000'')' into registered;
    if registered then
      raise exception 'BOX_B_GUARD: migration version 20261013130000 already registered';
    end if;
  end if;
end;
$$;
-- ===== migration 20261013130000_market_outcome_box_b_authority_v1.sql (verbatim) =====
"""
    verify = f"""
-- ===== fail-closed verification before COMMIT =====
do $$
declare bad text;
begin
  if (select count(*) from public.market_outcome_revisions) <> {n_rev}
     or (select count(*) from public.market_outcome_provider_receipts) <> {n_rc} then
    raise exception 'BOX_B_VERIFY: unexpected row counts';
  end if;
  if exists (select 1 from public.market_outcome_revisions r
              join public.market_outcome_provider_receipts g on g.receipt_id = r.gamma_receipt_id
             where r.outcome_status in ('FINAL', 'VOID')
               and r.resolved_at is distinct from (g.raw_body::jsonb -> 0 ->> 'closedTime')::timestamptz) then
    raise exception 'BOX_B_VERIFY: resolved_at not backed by gamma closedTime';
  end if;
  if exists (select 1 from public.market_outcome_revisions where revision_no <> 1 or prev_revision_digest is not null) then
    raise exception 'BOX_B_VERIFY: unexpected revision chain';
  end if;
  foreach bad in array array['anon', 'authenticated', 'public', 'blind_model_reader'] loop
    if bad = 'public' or exists (select 1 from pg_roles where rolname = bad) then
      if bad = 'public' then
        if exists (select 1 from information_schema.role_table_grants
                    where grantee = 'PUBLIC' and table_schema = 'public' and table_name like 'market_outcome_%') then
          raise exception 'BOX_B_VERIFY: PUBLIC has grants';
        end if;
        if has_function_privilege('public', 'public.market_outcome_validate_receipts(text,text,text,bigint,bigint,jsonb,timestamptz,text)', 'execute')
           or has_sequence_privilege('public', pg_get_serial_sequence('public.market_outcome_provider_receipts', 'receipt_id'), 'usage,select,update') then
          raise exception 'BOX_B_VERIFY: PUBLIC can execute/use Box B function or sequence';
        end if;
      elsif has_table_privilege(bad, 'public.market_outcome_revisions', 'select,insert,update,delete,truncate,references,trigger')
         or has_table_privilege(bad, 'public.market_outcome_provider_receipts', 'select,insert,update,delete,truncate,references,trigger')
         or has_table_privilege(bad, 'public.market_outcome_current', 'select')
         or has_function_privilege(bad, 'public.market_outcome_validate_receipts(text,text,text,bigint,bigint,jsonb,timestamptz,text)', 'execute')
         or has_sequence_privilege(bad, pg_get_serial_sequence('public.market_outcome_provider_receipts', 'receipt_id'), 'usage,select,update') then
        raise exception 'BOX_B_VERIFY: % has access', bad;
      end if;
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'service_role') and (
       has_table_privilege('service_role', 'public.market_outcome_revisions', 'update,delete,truncate')
    or has_table_privilege('service_role', 'public.market_outcome_provider_receipts', 'update,delete,truncate')
    or not has_table_privilege('service_role', 'public.market_outcome_revisions', 'select,insert')) then
    raise exception 'BOX_B_VERIFY: service_role privileges wrong';
  end if;
  if (select count(*) from pg_trigger where tgrelid in ('public.market_outcome_revisions'::regclass,
        'public.market_outcome_provider_receipts'::regclass) and not tgisinternal) <> 5 then
    raise exception 'BOX_B_VERIFY: guard triggers missing';
  end if;
end;
$$;
commit;
"""
    operator = guard + mig + ("\n" if not mig.endswith("\n") else "") + "-- ===== pilot insert =====\n" + pilot + verify
    (HERE / "pilot_insert.sql").write_text(pilot)
    (HERE / "operator_dbclone_box_b_v1.sql").write_text(operator)
    h = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    man = {"migration": {"path": str(MIG.relative_to(HERE.parents[1])), "sha256": h(MIG)},
           "pilot_insert_sha256": h(HERE / "pilot_insert.sql"),
           "operator_sql_sha256": h(HERE / "operator_dbclone_box_b_v1.sql"),
           "frozen_input_sha256": h(HERE / "market20_frozen_input.csv"),
           "receipts_index_sha256": h(RCPT / "receipts_index.json"),
           "receipt_rows": n_rc, "revision_rows": n_rev}
    (HERE / "build_manifest.json").write_text(json.dumps(man, indent=1) + "\n")
    print(json.dumps(man, indent=1))


main()
